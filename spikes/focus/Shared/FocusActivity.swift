import ActivityKit
import AppIntents
import Foundation

enum ProbeFiles {
  static let group = "group.dev.callkitsim.focus"
  static var documents: URL { FileManager.default.urls(for: .documentDirectory, in: .userDomainMask)[0] }
  static func write(_ name: String, data: Data) throws {
    let url = documents.appendingPathComponent(name)
    try data.write(to: url, options: [.atomic, .completeFileProtectionUntilFirstUserAuthentication])
  }
}

struct FocusAttributes: ActivityAttributes {
  let surfaceID: String
  struct ContentState: Codable, Hashable {
    var revision: Int
    var excerpt: String
    var updatedAt: Int64
  }
}

// Only synthetic, non-private text is generated by this measurement app.
enum FocusActivities {
  @MainActor static var observations: [String: Task<Void, Never>] = [:]
  @MainActor static var discovery: Task<Void, Never>?
  @MainActor static func discover() {
    for activity in Activity<FocusAttributes>.activities { observe(activity) }
    guard discovery == nil else { return }
    discovery = Task { @MainActor in
      for await activity in Activity<FocusAttributes>.activityUpdates { observe(activity) }
    }
  }
  @MainActor static func start() throws {
    guard ActivityAuthorizationInfo().areActivitiesEnabled else { throw ActivityAuthorizationError.denied }
    // Idempotent: the user may invoke the foreground button or LiveActivityIntent twice.
    guard Activity<FocusAttributes>.activities.isEmpty else { return }
    let content = FocusAttributes.ContentState(revision: 0, excerpt: "Synthetic AI call status", updatedAt: Int64(Date().timeIntervalSince1970))
    let activity = try Activity.request(attributes: FocusAttributes(surfaceID: UUID().uuidString),
      content: ActivityContent(state: content, staleDate: Date().addingTimeInterval(30)), pushType: .token)
    observe(activity)
  }
  @MainActor static func observe(_ activity: Activity<FocusAttributes>) {
    guard observations[activity.id] == nil else { return }
    observations[activity.id] = Task { @MainActor in
      for await token in activity.pushTokenUpdates {
        // Export only to the private container; never print or trace the token.
        let value = ["activityID": activity.id, "surfaceID": activity.attributes.surfaceID,
          "token": token.map { String(format: "%02x", $0) }.joined(), "attributesType": "FocusAttributes"]
        try? ProbeFiles.write("activity-update-token.json", data: JSONSerialization.data(withJSONObject: value))
      }
    }
  }
  @MainActor static func update() async {
    for activity in Activity<FocusAttributes>.activities {
      let revision = activity.content.state.revision + 1
      await activity.update(ActivityContent(state: .init(revision: revision,
        excerpt: "Synthetic transcript turn \(revision)", updatedAt: Int64(Date().timeIntervalSince1970)),
        staleDate: Date().addingTimeInterval(30))) // no alertConfiguration
    }
  }
  @MainActor static func end() async {
    for activity in Activity<FocusAttributes>.activities {
      await activity.end(nil, dismissalPolicy: .immediate)
      observations.removeValue(forKey: activity.id)?.cancel()
    }
    try? FileManager.default.removeItem(at: ProbeFiles.documents.appendingPathComponent("activity-update-token.json"))
  }
}

enum AIPolicy: String, AppEnum {
  case decline, screenWithAI
  static var typeDisplayRepresentation: TypeDisplayRepresentation = "AI call policy"
  static var caseDisplayRepresentations: [AIPolicy: DisplayRepresentation] = [
    .decline: "Decline", .screenWithAI: "AI screens calls"]
}

struct FocusPolicyIntent: SetFocusFilterIntent {
  static var title: LocalizedStringResource = "AI call policy"
  @Parameter(title: "Policy", default: .decline) var policy: AIPolicy
  var displayRepresentation: DisplayRepresentation { DisplayRepresentation(title: "AI policy: \(policy.rawValue)") }
  func perform() async throws -> some IntentResult {
    let defaults = UserDefaults(suiteName: ProbeFiles.group)!
    defaults.set(policy.rawValue, forKey: "focus.aiPolicy")
    defaults.set(Date().timeIntervalSince1970, forKey: "focus.policyUpdatedAt")
    return .result()
  }
}

struct StartFocusActivityIntent: LiveActivityIntent {
  static var title: LocalizedStringResource = "Start Focus transcript probe"
  @MainActor func perform() async throws -> some IntentResult {
    try FocusActivities.start()
    return .result()
  }
}

struct FocusShortcuts: AppShortcutsProvider {
  static var appShortcuts: [AppShortcut] {
    AppShortcut(intent: StartFocusActivityIntent(), phrases: ["Start transcript in \(.applicationName)"],
      shortTitle: "Start transcript", systemImageName: "captions.bubble")
  }
}
