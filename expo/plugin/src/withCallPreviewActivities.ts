import type { ExpoConfig } from "expo/config";
import {
  type ConfigPlugin,
  IOSConfig,
  withInfoPlist,
  withPodfile,
  withXcodeProject,
  type XcodeProject,
} from "expo/config-plugins";
import { mkdirSync, writeFileSync } from "fs";
import { join } from "path";


const ERROR_MSG_PREFIX = "An error occurred while configuring call previews. ";

/** The widget extension that shows call previews' Live Activities. */
export const WIDGET_TARGET = "CallPreviewWidget";

/** The minimum iOS version of ios-voip-sdk, and so of the widget extension. */
const MINIMUM_IOS = "26.0";

const WIDGET_POD_MARKER = "# @relayphone/ios-voip-sdk: call preview widget";

/**
 * The widget extension's files, which prebuild writes to `ios/CallPreviewWidget`. Its Info.plist
 * has the app's version and build number, as an app extension must.
 */
export function widgetFiles(config: ExpoConfig): Record<WidgetFile, string> {
  return {
    "CallPreviewWidget.swift": `// Generated by @relayphone/ios-voip-sdk's config plugin. Prebuild replaces this file; to show call
// previews with your own views, set \`callPreviewActivities: { widgetExtension: false }\` and
// add your own widget extension.
internal import VoIPConversations
import SwiftUI
import WidgetKit

/// The widget extension, which shows call previews' Live Activities.
@main
struct CallPreviewWidgetBundle: WidgetBundle {
  var body: some Widget {
    CallPreviewWidget()
  }
}

/// A call preview's Live Activity, with ios-voip-sdk's default views and the app's Join intent.
struct CallPreviewWidget: Widget {
  var body: some WidgetConfiguration {
    ActivityConfiguration(for: CallPreviewAttributes.self) { context in
      CallPreviewView(context, join: JoinCallPreview.self)
    } dynamicIsland: { context in
      CallPreviewView.dynamicIsland(context, join: JoinCallPreview.self)
    }
  }
}
`,
    "JoinCallPreview.swift": `// Generated by @relayphone/ios-voip-sdk's config plugin. Prebuild replaces this file.
import AppIntents
internal import VoIPConversations

/// The Join button of a call preview's Live Activity. The app and its call preview widget both
/// compile this file: the widget shows the button, and the system opens the app and performs the
/// intent there, which joins the call.
struct JoinCallPreview: JoinCallPreviewIntent {
  static let title: LocalizedStringResource = "Join Call"
  static let supportedModes: IntentModes = .foreground(.immediate)
  static let isDiscoverable = false

  @Parameter(title: "Call ID")
  var callID: String
}
`,
    "Info.plist": `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyLists-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDisplayName</key>
	<string>${WIDGET_TARGET}</string>
	<key>CFBundleShortVersionString</key>
	<string>${xml(IOSConfig.Version.getVersion(config))}</string>
	<key>CFBundleVersion</key>
	<string>${xml(IOSConfig.Version.getBuildNumber(config))}</string>
	<key>NSExtension</key>
	<dict>
		<key>NSExtensionPointIdentifier</key>
		<string>com.apple.widgetkit-extension</string>
	</dict>
</dict>
</plist>
`,
  };
}

function xml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

type WidgetFile =
  | "CallPreviewWidget.swift"
  | "JoinCallPreview.swift"
  | "Info.plist";

const WIDGET_FILE_NAMES: readonly WidgetFile[] = [
  "CallPreviewWidget.swift",
  "JoinCallPreview.swift",
  "Info.plist",
];

/** The file that both the app and the widget extension compile. */
const SHARED_FILE = "JoinCallPreview.swift";

export type CallPreviewActivitiesOption =
  | boolean
  | {
      /**
       * Generates the `CallPreviewWidget` widget extension, which shows call previews with
       * ios-voip-sdk's default views, and the Join intent that the app and the extension share.
       * Set it to false to show call previews from your own widget extension.
       * @default true
       */
      widgetExtension?: boolean;
    };

/** The PBXProject objects, by section and then by identifier. */
type Objects = Record<string, Record<string, unknown>>;

interface BuildPhase {
  files: { value: string; comment: string }[];
}

interface Group {
  children: { value: string; comment: string }[];
}

interface BuildConfiguration {
  name: string;
  buildSettings: Record<string, unknown>;
}

/**
 * Adds the `CallPreviewWidget` widget extension to the Xcode project, embedded in the app, with
 * the generated sources in `ios/CallPreviewWidget`, and adds the shared Join intent to the app
 * target. A project that has the target already is returned unchanged.
 */
export function addCallPreviewWidget(
  project: XcodeProject,
  {
    projectName,
    bundleIdentifier,
    config,
  }: { projectName: string; bundleIdentifier: string; config: ExpoConfig },
): XcodeProject {
  if (hasWidgetTarget(project)) return project;
  const app = IOSConfig.XcodeUtils.getApplicationNativeTarget({
    project,
    projectName,
  });
  // `addTarget` embeds the extension in, and makes a dependency of, the project's first target.
  if (project.getFirstTarget().uuid !== app.uuid) {
    throw new Error(
      `${ERROR_MSG_PREFIX}The app must be the Xcode project's first target.`,
    );
  }
  const objects = project.hash.project.objects as Objects;
  // A project with one target has neither section, which `addTarget` needs.
  objects.PBXTargetDependency ??= {};
  objects.PBXContainerItemProxy ??= {};

  const appPhases = (app.target.buildPhases as { value: string }[]).length;
  const target = project.addTarget(
    WIDGET_TARGET,
    "app_extension",
    WIDGET_TARGET,
    `${bundleIdentifier}.${WIDGET_TARGET}`,
  ) as {
    uuid: string;
    pbxNativeTarget: {
      buildConfigurationList: string;
      productReference: string;
    };
  };
  embedWidget(
    objects,
    app.target.buildPhases as { value: string }[],
    appPhases,
    target,
  );

  // The extension's files, in a group of their own.
  const group = project.addPbxGroup([], WIDGET_TARGET, WIDGET_TARGET) as {
    uuid: string;
    pbxGroup: Group;
  };
  const references: Record<string, string> = {};
  for (const name of WIDGET_FILE_NAMES) {
    references[name] = addFileReference(objects, project, group.pbxGroup, name);
  }
  const mainGroup = project.getFirstProject().firstProject.mainGroup as string;
  (project.getPBXGroupByKey(mainGroup) as Group).children.push({
    value: group.uuid,
    comment: WIDGET_TARGET,
  });

  const sources = (
    project.addBuildPhase(
      [],
      "PBXSourcesBuildPhase",
      "Sources",
      target.uuid,
    ) as {
      buildPhase: BuildPhase;
    }
  ).buildPhase;
  for (const name of ["CallPreviewWidget.swift", SHARED_FILE]) {
    addBuildFile(objects, project, sources, references[name]!, name, "Sources");
  }
  project.addBuildPhase([], "PBXResourcesBuildPhase", "Resources", target.uuid);
  project.addBuildPhase(
    [],
    "PBXFrameworksBuildPhase",
    "Frameworks",
    target.uuid,
  );

  // The app performs the Join intent, so it compiles the intent too.
  const appSources = project.pbxSourcesBuildPhaseObj(
    app.uuid,
  ) as BuildPhase | null;
  if (!appSources) {
    throw new Error(
      `${ERROR_MSG_PREFIX}The app target has no Sources build phase.`,
    );
  }
  addBuildFile(
    objects,
    project,
    appSources,
    references[SHARED_FILE]!,
    SHARED_FILE,
    "Sources",
  );

  const appSettings = buildConfigurations(
    project,
    app.target.buildConfigurationList as string,
  );
  for (const configuration of buildConfigurations(
    project,
    target.pbxNativeTarget.buildConfigurationList,
  )) {
    const inherited =
      appSettings.find(({ name }) => name === configuration.name)
        ?.buildSettings ?? {};
    Object.assign(configuration.buildSettings, {
      INFOPLIST_FILE: `${WIDGET_TARGET}/Info.plist`,
      GENERATE_INFOPLIST_FILE: "YES",
      MARKETING_VERSION: IOSConfig.Version.getVersion(config),
      CURRENT_PROJECT_VERSION: IOSConfig.Version.getBuildNumber(config),
      SWIFT_VERSION: "6.0",
      IPHONEOS_DEPLOYMENT_TARGET: deploymentTarget(
        inherited.IPHONEOS_DEPLOYMENT_TARGET,
      ),
      TARGETED_DEVICE_FAMILY: inherited.TARGETED_DEVICE_FAMILY ?? '"1,2"',
      CODE_SIGN_STYLE: "Automatic",
      ...pick(inherited, ["DEVELOPMENT_TEAM"]),
    });
  }
  return project;
}

/** Whether the project has the widget extension's target, from an earlier prebuild. */
function hasWidgetTarget(project: XcodeProject): boolean {
  const targets =
    (project.hash.project.objects as Objects).PBXNativeTarget ?? {};
  return Object.values(targets).some(
    (target) =>
      typeof target === "object" &&
      target !== null &&
      String((target as { name?: unknown }).name).replace(/"/g, "") ===
        WIDGET_TARGET,
  );
}

/**
 * Makes the build phase that `addTarget` added to the app embed the extension, as Xcode's
 * "Embed Foundation Extensions" phase does. `addTarget` puts the product in the project's first
 * "Copy Files" phase, which may be another extension's, and leaves undefined attributes on the
 * product's file reference.
 */
function embedWidget(
  objects: Objects,
  appPhases: { value: string; comment?: string }[],
  existingPhases: number,
  target: { pbxNativeTarget: { productReference: string } },
): void {
  const product = target.pbxNativeTarget.productReference;
  const reference = objects.PBXFileReference![product] as Record<
    string,
    unknown
  >;
  for (const key of Object.keys(reference)) {
    if (reference[key] === undefined) delete reference[key];
  }
  const copies = objects.PBXCopyFilesBuildPhase as Record<
    string,
    BuildPhase & { name?: string }
  >;
  const buildFiles = objects.PBXBuildFile as Record<
    string,
    { fileRef?: string }
  >;
  const isProduct = ({ value }: { value: string }) =>
    buildFiles[value]?.fileRef === product;
  let buildFile: { value: string; comment: string } | undefined;
  for (const key of Object.keys(copies)) {
    const phase = copies[key];
    if (typeof phase !== "object" || !phase.files) continue;
    buildFile ??= phase.files.find(isProduct);
    phase.files = phase.files.filter((file) => !isProduct(file));
  }
  const embed = appPhases[existingPhases];
  const phase = embed && copies[embed.value];
  if (!embed || !phase || !buildFile) {
    throw new Error(
      `${ERROR_MSG_PREFIX}Unable to embed the widget extension in the app.`,
    );
  }
  const name = "Embed Foundation Extensions";
  buildFile.comment = `${WIDGET_TARGET}.appex in ${name}`;
  objects.PBXBuildFile![`${buildFile.value}_comment`] = buildFile.comment;
  phase.files.push(buildFile);
  phase.name = `"${name}"`;
  copies[`${embed.value}_comment`] = name as never;
  embed.comment = name;
}

/** Adds a file in the extension's group, and returns its file reference. */
function addFileReference(
  objects: Objects,
  project: XcodeProject,
  group: Group,
  name: string,
): string {
  const uuid = project.generateUuid() as string;
  const fileType = name.endsWith(".swift")
    ? "sourcecode.swift"
    : "text.plist.xml";
  objects.PBXFileReference![uuid] = {
    isa: "PBXFileReference",
    lastKnownFileType: fileType,
    path: name,
    sourceTree: '"<group>"',
  };
  objects.PBXFileReference![`${uuid}_comment`] = name;
  group.children.push({ value: uuid, comment: name });
  return uuid;
}

/** Adds a file to a target's build phase. */
function addBuildFile(
  objects: Objects,
  project: XcodeProject,
  phase: BuildPhase,
  fileRef: string,
  name: string,
  phaseName: string,
): void {
  const uuid = project.generateUuid() as string;
  const comment = `${name} in ${phaseName}`;
  objects.PBXBuildFile![uuid] = {
    isa: "PBXBuildFile",
    fileRef,
    fileRef_comment: name,
  };
  objects.PBXBuildFile![`${uuid}_comment`] = comment;
  phase.files.push({ value: uuid, comment });
}

/** The build configurations of a configuration list. */
function buildConfigurations(
  project: XcodeProject,
  listID: string,
): BuildConfiguration[] {
  const lists = project.pbxXCConfigurationList() as Record<
    string,
    { buildConfigurations: { value: string }[] }
  >;
  const section = project.pbxXCBuildConfigurationSection() as Record<
    string,
    BuildConfiguration
  >;
  return (lists[listID]?.buildConfigurations ?? []).flatMap(({ value }) =>
    section[value] ? [section[value]] : [],
  );
}

/** The app's deployment target, or the SDK's minimum when the app's is lower. */
function deploymentTarget(app: unknown): string {
  const version = typeof app === "string" ? app.replace(/"/g, "") : "";
  return Number.parseFloat(version) > Number.parseFloat(MINIMUM_IOS)
    ? version
    : MINIMUM_IOS;
}

function pick(
  settings: Record<string, unknown>,
  keys: string[],
): Record<string, unknown> {
  return Object.fromEntries(
    keys.flatMap((key) => (key in settings ? [[key, settings[key]]] : [])),
  );
}

/**
 * Adds the widget extension's target to the Podfile, with ios-voip-sdk's `LiveActivity` subspec
 * from the installed package. Running it again replaces the block it added.
 */
export function addWidgetPods(podfile: string): string {
  const start = podfile.indexOf(WIDGET_POD_MARKER);
  const base =
    start < 0
      ? podfile
      : podfile.slice(0, start) +
        podfile.slice(podfile.indexOf("end\n", start) + "end\n".length);
  return (
    base.replace(/\n*$/, "\n") +
    `\n${WIDGET_POD_MARKER}\n` +
    `target '${WIDGET_TARGET}' do\n` +
    `  pod 'VoIPConversations/LiveActivity', :path => Pathname.new(File.join(File.dirname(\n` +
    `    Pod::Executable.execute_command('node', ['--print',\n` +
    `      "require.resolve('@relayphone/ios-voip-sdk/package.json', { paths: [process.argv[1]] })", __dir__]).strip), 'ios')).relative_path_from(Pathname.new(__dir__)).to_s\n` +
    `end\n`
  );
}

/**
 * Declares the widget extension for EAS Build, which then creates its credentials:
 * `extra.eas.build.experimental.ios.appExtensions`.
 */
export function withWidgetCredentials(
  config: ExpoConfig,
  bundleIdentifier: string,
): ExpoConfig {
  const extra = record(config.extra);
  const eas = record(extra.eas);
  const build = record(eas.build);
  const experimental = record(build.experimental);
  const ios = record(experimental.ios);
  const extensions = (
    Array.isArray(ios.appExtensions) ? ios.appExtensions : []
  ).filter((entry: unknown) => record(entry).targetName !== WIDGET_TARGET);
  extensions.push({
    targetName: WIDGET_TARGET,
    bundleIdentifier: `${bundleIdentifier}.${WIDGET_TARGET}`,
    entitlements: {},
  });
  config.extra = {
    ...extra,
    eas: {
      ...eas,
      build: {
        ...build,
        experimental: {
          ...experimental,
          ios: { ...ios, appExtensions: extensions },
        },
      },
    },
  };
  return config;
}

function record(value: unknown): Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {};
}

/**
 * Shows call previews as Live Activities: the module's podspec adds ios-voip-sdk's
 * `LiveActivity` subspec from the Podfile properties, the app supports Live Activities, and,
 * unless the app brings its own, the `CallPreviewWidget` widget extension shows them.
 */
export const withCallPreviewActivities: ConfigPlugin<{
  callPreviewActivities?: CallPreviewActivitiesOption;
}> = (config, { callPreviewActivities }) => {
  if (!callPreviewActivities) return config;
  config = withInfoPlist(config, (config) => {
    config.modResults.NSSupportsLiveActivities = true;
    return config;
  });
  const widgetExtension =
    callPreviewActivities === true ||
    callPreviewActivities.widgetExtension !== false;
  if (!widgetExtension) return config;

  const bundleIdentifier = config.ios?.bundleIdentifier;
  if (!bundleIdentifier) {
    throw new Error(
      `${ERROR_MSG_PREFIX}The call preview widget's bundle identifier derives from ` +
        `"ios.bundleIdentifier", which isn't set.`,
    );
  }
  config = withWidgetCredentials(config, bundleIdentifier);
  config = withXcodeProject(config, (config) => {
    const projectName = config.modRequest.projectName;
    if (!projectName) {
      throw new Error(
        `${ERROR_MSG_PREFIX}Unable to find the iOS project name.`,
      );
    }
    const directory = join(
      config.modRequest.platformProjectRoot,
      WIDGET_TARGET,
    );
    mkdirSync(directory, { recursive: true });
    for (const [name, contents] of Object.entries(widgetFiles(config))) {
      writeFileSync(join(directory, name), contents);
    }
    config.modResults = addCallPreviewWidget(config.modResults, {
      projectName,
      bundleIdentifier,
      config,
    });
    return config;
  });
  return withPodfile(config, (config) => {
    config.modResults.contents = addWidgetPods(config.modResults.contents);
    return config;
  });
};
